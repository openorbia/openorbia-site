#!/usr/bin/env node
// Give every link to a CSS or JS file in public/assets/ a version: /assets/launch.css?v=<first 10 hex of its SHA-256>.
// A changed file gets a new address, so browsers fetch it fresh after a deploy instead of using a cached copy that no longer
// matches the page. (openorbia.com's Cloudflare "Browser Cache TTL" keeps /assets/ files for 4 hours whatever public/_headers says.)
//
//   node scripts/stamp-assets.mjs     (npm run stamp; npm run deploy runs it first)
//
// It writes:
//   - the imports between modules in public/assets/ (tools.js imports ./logos.js?v=...), leaves first, so a module's version
//     also changes when something it imports changes
//   - the links in the static pages (public/index.html, public/launch-list/index.html, public/404.html)
//   - lib/asset-versions.js, which the server-rendered pages use (layout.js, form-pages.js)
// Running it again with nothing changed changes nothing. test/assets.test.js fails when a version is out of date.

import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const assets = join(root, 'public', 'assets');
const PAGES = ['public/index.html', 'public/launch-list/index.html', 'public/404.html'];

export const hashOf = text => createHash('sha256').update(text).digest('hex').slice(0, 10);
const names = readdirSync(assets).filter(f => /\.(css|js)$/.test(f)).sort();
// "./tools.js" or "./tools.js?v=0123456789" inside a module
const IMPORT_RE = /(from\s*["'])\.\/([a-z0-9-]+\.js)(?:\?v=[0-9a-f]+)?(["'])/g;
// "/assets/launch.css" or "/assets/launch.css?v=0123456789" in a page
const LINK_RE = /(["'])\/assets\/([a-z0-9-]+\.(?:css|js))(?:\?v=[0-9a-f]+)?(["'])/g;

const read = f => readFileSync(join(assets, f), 'utf8');
const deps = Object.fromEntries(names.map(f => [f, [...read(f).matchAll(IMPORT_RE)].map(m => m[2])]));

// leaves first: a module is stamped after everything it imports
const versions = {};
const visit = (f, path = []) => {
  if (versions[f]) return;
  if (path.includes(f)) throw new Error(`import cycle: ${[...path, f].join(' -> ')}`);
  for (const d of deps[f]) {
    if (!names.includes(d)) throw new Error(`${f} imports ./${d}, which is not in public/assets/`);
    visit(d, [...path, f]);
  }
  const before = read(f);
  const after = before.replace(IMPORT_RE, (_, a, d, b) => `${a}./${d}?v=${versions[d]}${b}`);
  if (after !== before) writeFileSync(join(assets, f), after);
  versions[f] = hashOf(after);
};
names.forEach(f => visit(f));

let changed = 0;
for (const page of PAGES) {
  const file = join(root, page), before = readFileSync(file, 'utf8');
  const after = before.replace(LINK_RE, (all, a, f, b) => (versions[f] ? `${a}/assets/${f}?v=${versions[f]}${b}` : all));
  if (after !== before) { writeFileSync(file, after); changed++; }
}

const out = join(root, 'lib', 'asset-versions.js');
const js = `// Generated by scripts/stamp-assets.mjs (npm run stamp). Do not edit by hand.\n` +
  `// The version of each file in public/assets/: the first 10 hex of its SHA-256, after its own imports were stamped.\n` +
  `export const VERSIONS = ${JSON.stringify(versions, null, 1).replace(/\n\s*/g, ' ')};\n\n` +
  `// "launch.css" -> "/assets/launch.css?v=0123456789"\n` +
  `export const asset = name => \`/assets/\${name}?v=\${VERSIONS[name]}\`;\n`;
let old = '';
try { old = readFileSync(out, 'utf8'); } catch {}
if (old !== js) { writeFileSync(out, js); changed++; }
console.log(`${names.length} assets versioned; ${changed ? `${changed} file(s) updated` : 'nothing changed'}.`);
