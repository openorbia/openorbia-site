#!/usr/bin/env node
// Download the logo of each Launch List tool whose GitHub owner is an organization (its avatar is the project's logo) into
// public/logos/<slug>.<png|jpg|webp>, and write public/assets/logos.js with the ones we have. Tools owned by a personal
// account keep the letter tile: a person's profile photo is not a tool logo. The images are served from openorbia.com, so a
// visitor's browser never asks GitHub for them.
//
//   node scripts/fetch-logos.mjs            fetch logos that are missing, keep the ones already there
//   node scripts/fetch-logos.mjs --refresh  fetch them all again
//
// Run it after adding tools to public/assets/tools.js, then commit public/logos/ and public/assets/logos.js and deploy.

import { writeFileSync, mkdirSync, existsSync, readdirSync, unlinkSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
// tools.js imports logos.js, so it has to exist before tools.js can be read
const logosFile = join(root, 'public', 'assets', 'logos.js');
if (!existsSync(logosFile)) writeFileSync(logosFile, 'export const LOGOS = {};\n');
const { ROWS, slugOf } = await import('../public/assets/tools.js');
const dir = join(root, 'public', 'logos');
const refresh = process.argv.includes('--refresh');
const TYPES = { 'image/png': 'png', 'image/jpeg': 'jpg', 'image/webp': 'webp' };   // never SVG: it can carry script
const MAX_BYTES = 200_000;
const headers = { 'user-agent': 'openorbia-site fetch-logos', accept: 'application/vnd.github+json' };
if (process.env.GITHUB_TOKEN) headers.authorization = `Bearer ${process.env.GITHUB_TOKEN}`;

mkdirSync(dir, { recursive: true });
const have = Object.fromEntries(readdirSync(dir).map(f => [f.replace(/\.[a-z]+$/, ''), f]));
const logos = {};
let fetched = 0, skipped = 0;

for (const [name, repo] of ROWS) {
  const slug = slugOf(name), owner = repo.split('/')[0];
  if (!refresh && have[slug]) { logos[slug] = `/logos/${have[slug]}`; continue; }
  const u = await fetch(`https://api.github.com/users/${encodeURIComponent(owner)}`, { headers });
  if (!u.ok) { console.error(`${name}: GitHub answered ${u.status} for ${owner}`); process.exitCode = 1; continue; }
  const user = await u.json();
  if (user.type !== 'Organization') { skipped++; continue; }
  const img = await fetch(`${user.avatar_url}${user.avatar_url.includes('?') ? '&' : '?'}s=128`);
  const ext = TYPES[(img.headers.get('content-type') || '').split(';')[0]];
  const bytes = Buffer.from(await img.arrayBuffer());
  if (!img.ok || !ext || bytes.length > MAX_BYTES) { console.error(`${name}: not a usable image (${img.status}, ${img.headers.get('content-type')}, ${bytes.length} bytes)`); process.exitCode = 1; continue; }
  if (have[slug] && have[slug] !== `${slug}.${ext}`) unlinkSync(join(dir, have[slug]));
  writeFileSync(join(dir, `${slug}.${ext}`), bytes);
  logos[slug] = `/logos/${slug}.${ext}`;
  fetched++;
}

const sorted = Object.fromEntries(Object.entries(logos).sort(([a], [b]) => a.localeCompare(b)));
writeFileSync(logosFile,
  `// Generated by scripts/fetch-logos.mjs: the tools whose logo is in public/logos/ (organization avatars from GitHub). Do not edit by hand.\n` +
  `export const LOGOS = ${JSON.stringify(sorted, null, 1).replace(/\n\s*/g, ' ')};\n`);
console.log(`${Object.keys(sorted).length} logos (${fetched} fetched now), ${skipped} tools owned by a person keep the letter tile.`);
